def _validate():
    """Fail import if a table is misaligned with its canonical 'en' or misses a language."""
    for name, table in TABLES.items():
        n = len(table["en"])
        missing = [lang for lang in LANGS if lang not in table]
        if missing:
            raise ValueError(f"translations.{name} is missing languages {missing}")
        for lang, arr in table.items():
            if len(arr) != n:
                raise ValueError(
                    f"translations.{name}[{lang}] has {len(arr)} entries, expected {n}"
                )
    for name, table in DICTS.items():
        entries = table.values() if name != "sankranti_suffix" else [table]
        for entry in entries:
            missing = [lang for lang in LANGS if lang not in entry]
            if missing:
                raise ValueError(f"translations.{name} entry {entry} is missing {missing}")


_validate()
